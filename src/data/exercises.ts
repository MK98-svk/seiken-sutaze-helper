export function exercisesFor(mode: WorkoutMode, group?: MuscleGroup) {
  return EXERCISES.filter((e) => e.modes.includes(mode) && (!group || e.group === group));
}

export function groupsFor(mode: WorkoutMode) {
  return GROUPS.filter((g) => EXERCISES.some((e) => e.modes.includes(mode) && e.group === g.id));
}

export function exerciseById(id: string) {
  return EXERCISES.find((e) => e.id === id);
}


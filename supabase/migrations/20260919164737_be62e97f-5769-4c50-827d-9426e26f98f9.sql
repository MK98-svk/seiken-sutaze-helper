CREATE TABLE public.club_trainings (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  datum date NOT NULL UNIQUE,
  typ text NOT NULL CHECK (typ IN ('vsetci','kata','kumite')),
  cas_od time NOT NULL,
  cas_do time NOT NULL,
  trenujeme boolean NOT NULL DEFAULT true,
  poznamka text,
  odcvicene boolean NOT NULL DEFAULT false,
  odcvicene_at timestamptz,
  odcvicene_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.club_trainings TO authenticated;
GRANT ALL ON public.club_trainings TO service_role;

ALTER TABLE public.club_trainings ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Prihlaseni vidia treningy" ON public.club_trainings
  FOR SELECT TO authenticated USING (true);
CREATE POLICY "Admin a trener pridava treningy" ON public.club_trainings
  FOR INSERT TO authenticated WITH CHECK (private.has_role(auth.uid(),'admin') OR private.has_role(auth.uid(),'coach'));
CREATE POLICY "Admin a trener upravuje treningy" ON public.club_trainings
  FOR UPDATE TO authenticated USING (private.has_role(auth.uid(),'admin') OR private.has_role(auth.uid(),'coach'))
  WITH CHECK (private.has_role(auth.uid(),'admin') OR private.has_role(auth.uid(),'coach'));
CREATE POLICY "Admin maze treningy" ON public.club_trainings
  FOR DELETE TO authenticated USING (private.has_role(auth.uid(),'admin'));

CREATE TRIGGER club_trainings_updated_at
  BEFORE UPDATE ON public.club_trainings
  FOR EACH ROW EXECUTE FUNCTION public.update_updated_at();

CREATE INDEX idx_club_trainings_datum ON public.club_trainings (datum);

